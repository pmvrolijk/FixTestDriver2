    private void jButtonOkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonOkActionPerformed
        //store the changed values
        cm.setProperty("ExpectMessageStep.timeout", Integer.toString(jSliderTimeout.getValue()));
        if (jTextFieldIgnoreTags.getBackground()!=Color.red)
            cm.setProperty("TestMessage.skipTags",jTextFieldIgnoreTags.getText());
        if (jCheckBoxCheckDate.isSelected()){
            cm.setProperty("TestMessage.checkDateTags","true");
        } else {
            cm.setProperty("TestMessage.checkDateTags","false");
        };
        if (jCheckBoxIgnoreUnexpect.isSelected()){
            cm.setProperty("TestMessage.ignoreUnexpectedTags","true");
        } else {
            cm.setProperty("TestMessage.ignoreUnexpectedTags","false");
        };
        if (jCheckBoxClordid.isSelected()){
            cm.setProperty("TestMessage.matchClordid","true");
        } else {
            cm.setProperty("TestMessage.matchClordid","false");
        };
        if (jCheckBoxMsgType.isSelected()){
            cm.setProperty("TestMessage.matchMsgType","true");
        } else {
            cm.setProperty("TestMessage.matchMsgType","false");
        };
        this.setVisible(false);
        this.dispose();
    }//GEN-LAST:event_jButtonOkActionPerformed

