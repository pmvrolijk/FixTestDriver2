    public EditPreferences(java.awt.Frame parent, boolean modal) {
        super(parent, modal);
        initComponents();
        //Get configuration
        cm=ConfigurationManager.getConfigurationManager();
        //Set time out value
        String toVal=cm.getProperty("ExpectMessageStep.timeout", "10000");
        this.timeout=Integer.parseInt(toVal);
        jSliderTimeout.setValue(this.timeout);
        selTimeout.setText(Integer.toString(jSliderTimeout.getValue()));
        //Set Test Message values
        this.ignoreUnexpectedTags=cm.getProperty("TestMessage.ignoreUnexpectedTags","false");
        if (this.ignoreUnexpectedTags.equalsIgnoreCase("true")) {
            jCheckBoxIgnoreUnexpect.setSelected(true);
        } else {
            jCheckBoxIgnoreUnexpect.setSelected(false);
        };
        this.checkDateTags=cm.getProperty("TestMessage.checkDateTags","false");
        if (this.checkDateTags.equalsIgnoreCase("true")) {
            jCheckBoxCheckDate.setSelected(true);
        } else {
            jCheckBoxCheckDate.setSelected(false);
        };
        skipTags=cm.getProperty("TestMessage.skipTags","");
        jTextFieldIgnoreTags.setText(skipTags);
        this.matchMsgType=cm.getProperty("TestMessage.matchMsgType","true");
        if (this.matchMsgType.equalsIgnoreCase("true")) {
            jCheckBoxMsgType.setSelected(true);
        } else {
            jCheckBoxMsgType.setSelected(false);
        };
        this.matchClordid=cm.getProperty("TestMessage.matchClordid","false");
        if (this.matchClordid.equalsIgnoreCase("true")) {
            jCheckBoxClordid.setSelected(true);
        } else {
            jCheckBoxClordid.setSelected(false);
        };


        //Input verifiers
        InputVerifier verifier = new InputVerifier() {
        public boolean verify(JComponent input) {
                final JTextComponent source = (JTextComponent)input;
                String text = source.getText();
                if (!text.matches("[0-9,]*")) {
                    source.setBackground(Color.red);
                    ToolTipManager.sharedInstance().mouseMoved(
                        new MouseEvent(source, 0, 0, 0,
                        0, 0, // X-Y of the mouse for the tool tip
                        0, false));
                    return false;
                } else {
                    source.setBackground(Color.white);
                    return true;
                }
            }
        };
        jTextFieldIgnoreTags.setInputVerifier(verifier);

    }

